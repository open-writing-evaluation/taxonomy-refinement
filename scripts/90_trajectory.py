#!/usr/bin/env python3
"""Assemble the headline trajectory tables across rounds.

Reads the agreement JSONs written by 50_agreement.py for the panel runs
(r1, ctrl, r2, r3) on d_ref and d_test, plus the within-model repeat-run
(floor) JSONs, and emits:

  outputs/results/trajectory_main.tex     layers x rounds (pairwise% / kappa),
                                          D_ref and D_test blocks
  outputs/results/trajectory_floor.tex    within-model floor vs. panel
  outputs/results/trajectory.json         machine-readable tables

Usage:
    python scripts/90_trajectory.py --panel claude,gpt,qwen,deepseek,kimi
"""
import argparse
import glob
import json
import os

RUNS = ['r1', 'ctrl', 'r2', 'r3']
RUN_LABEL = {'r1': 'T(1)', 'ctrl': 'T(1+)', 'r2': 'T(2)', 'r3': 'T(3)'}
LAYERS = ['screen', 'olabel', 'op', 'dom', 'pos', 'ext', 'comp']
LAYER_NAMES = {'screen': 'Screening', 'olabel': 'Orth.\\ label',
               'op': 'Operation', 'dom': 'Domain', 'pos': 'POS',
               'ext': 'Extension', 'comp': 'Composite (exact)'}


def load(run, sample, panel_slug):
    path = os.path.join('outputs', 'results',
                        f'{run}_agreement.{sample}.{panel_slug}.json')
    return json.load(open(path)) if os.path.exists(path) else None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--panel', default='claude,gpt,qwen,deepseek,kimi')
    args = ap.parse_args()
    slug = '+'.join(args.panel.split(','))

    data = {(run, s): load(run, s, slug)
            for run in RUNS for s in ('d_ref', 'd_test')}
    present = {k: v for k, v in data.items() if v}
    if not present:
        raise SystemExit('no agreement JSONs found - run 50_agreement.py first')

    outdir = os.path.join('outputs', 'results')
    os.makedirs(outdir, exist_ok=True)

    # ---------------- main table ------------------------------------------
    def cell(run, s, layer):
        d = data.get((run, s))
        if not d:
            return '--'
        t = d['table'].get(layer, {})
        if not t.get('n'):
            return '--'
        return f"{100*t['pairwise']:.1f} / {t['fleiss']:.3f}"

    with open(os.path.join(outdir, 'trajectory_main.tex'), 'w') as f:
        f.write('% auto-generated by 90_trajectory.py: pairwise% / Fleiss kappa\n')
        for s, title in (('d_ref', 'Refinement set $D_{\\mathrm{ref}}$'),
                         ('d_test', 'Held-out set $D_{\\mathrm{test}}$')):
            f.write(f'% ---- {title} ----\n')
            for layer in LAYERS:
                cells = ' & '.join(cell(run, s, layer) for run in RUNS)
                f.write(f'{LAYER_NAMES[layer]} & {cells} \\\\\n')
            for extra, key in (('Partial credit', 'partial'),
                               ('Unanimity', 'unanimity')):
                vals = []
                for run in RUNS:
                    d = data.get((run, s))
                    if not d:
                        vals.append('--')
                        continue
                    t = d['table'].get(key, {})
                    v = t.get('mean', t.get('rate'))
                    vals.append(f'{100*v:.1f}' if v is not None else '--')
                f.write(f'{extra} & ' + ' & '.join(vals) + ' \\\\\n')
            f.write('\n')

    # ---------------- floor table -----------------------------------------
    floor_rows = []
    for path in sorted(glob.glob(os.path.join(
            outdir, '*_agreement.*.*_rep2.json'))):
        d = json.load(open(path))
        base = d['models'][0]
        t = d['table']['comp']
        floor_rows.append((d['run'], d['sample'], base,
                           100 * t['pairwise'], t['fleiss']))
    with open(os.path.join(outdir, 'trajectory_floor.tex'), 'w') as f:
        f.write('% auto-generated by 90_trajectory.py\n')
        for run, sample, m, pw, fk in floor_rows:
            f.write(f'{RUN_LABEL.get(run, run)} & {sample} & {m} & '
                    f'{pw:.1f} & {fk:.3f} \\\\\n')

    # ---------------- gains in composite kappa ----------------------------
    gains = {}
    for s in ('d_ref', 'd_test'):
        if all(data.get((run, s)) for run in RUNS):
            k = {run: data[(run, s)]['table']['comp']['fleiss'] for run in RUNS}
            gains[s] = {'first_step': k['r2'] - k['r1'],
                        'both_steps': k['r3'] - k['r1'],
                        'rewording_alone': k['ctrl'] - k['r1'],
                        'rewording_share_of_first_step':
                            (k['ctrl'] - k['r1']) / (k['r2'] - k['r1'])}

    with open(os.path.join(outdir, 'trajectory.json'), 'w') as f:
        json.dump({'tables': {f'{run}.{s}': (d['table'] if d else None)
                              for (run, s), d in data.items()},
                   'kappa_gains': gains},
                  f, indent=2, default=float)
    print('wrote trajectory_main.tex, trajectory_floor.tex, trajectory.json')
    for (run, s), d in sorted(present.items()):
        t = d['table']['comp']
        print(f"  {run:5s} {s:7s} comp pairwise={100*t['pairwise']:.1f}% "
              f"kappa={t['fleiss']:.3f} (n={t['n']})")
    for s, g in gains.items():
        print(f"  {s:7s} kappa gain: first step {g['first_step']:.3f}, "
              f"both steps {g['both_steps']:.3f}, rewording alone "
              f"{g['rewording_alone']:.3f} "
              f"({100 * g['rewording_share_of_first_step']:.0f}% of the first step)")


if __name__ == '__main__':
    main()
